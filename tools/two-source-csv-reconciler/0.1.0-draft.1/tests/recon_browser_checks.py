"""Independent local headless Chromium / Playwright tests for sanitized Two-Source CSV Reconciler."""
import os,shutil
import asyncio,json,pathlib,traceback
from playwright.async_api import async_playwright
ROOT=pathlib.Path(__file__).resolve().parents[1]; TESTS=[]
def check(name,condition,detail=''):
    ok=bool(condition);TESTS.append({'test':name,'pass':ok,'detail':str(detail)[:450]});print(('PASS ' if ok else 'FAIL ')+name,flush=True)
    if not ok:raise AssertionError(name+' '+str(detail))
async def suite():
 async with async_playwright() as p:
  browser=await p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or shutil.which('chromium') or shutil.which('chromium-browser'),headless=True,args=['--no-sandbox'])
  page=await browser.new_page(accept_downloads=True);page.set_default_timeout(4500)
  requests=[];exceptions=[]
  page.on('request',lambda req:requests.append(req.url));page.on('pageerror',lambda ex:exceptions.append(str(ex)))
  h=(ROOT/'09_Two_Source_CSV_Reconciler.html').read_text().replace('<link rel="stylesheet" href="styles.css">','<style>'+(ROOT/'styles.css').read_text()+'</style>').replace('<script src="common.js"></script>','<script>'+(ROOT/'common.js').read_text()+'</script>')
  await page.set_content(h,wait_until='load')
  async def codes():return await page.locator('#results tr td:first-child').all_inner_texts()
  async def calc(source,target,fields=None,keyS=None,keyT=None,mode=None):
   if keyS is not None:await page.fill('#sourceKey',keyS)
   if keyT is not None:await page.fill('#targetKey',keyT)
   if fields is not None:await page.fill('#mapping',fields)
   if mode is not None:await page.select_option('#normalize',mode)
   await page.fill('#sourceText',source);await page.fill('#targetText',target);await page.click('#audit')
  async def blocked(msg):check(msg,'RECONCILIATION FAILED' in await page.locator('#status').inner_text() and await page.locator('#exportAI').is_disabled(),await page.locator('#err').inner_text())
  SH='item_id,label,qty';DH='product_code,product_name,units'
  SS=SH+'\nA-1,Widget A,5\nA-2,Widget B,4';DD=DH+'\nA-1,Widget A,5\nA-2,Widget B,4'
  check('startup mismatch has hold','HOLD' in await page.locator('#status').inner_text())
  c=await codes()
  check('duplicate source detected','DUPLICATE_KEY' in c)
  check('blank source key detected','BLANK_KEY' in c)
  check('missing destination row detected','MISSING_DESTINATION' in c)
  check('extra destination row detected','EXTRA_DESTINATION' in c)
  check('mismatched field detected','VALUE_MISMATCH' in c)
  check('source record count 6',await page.locator('#mSource').inner_text()=='6')
  check('destination count 4',await page.locator('#mTarget').inner_text()=='4')
  check('unique paired records 2',await page.locator('#mMatched').inner_text()=='2')
  check('exact compared cells 4',await page.locator('#mCompared').inner_text()=='4')
  check('no JS errors at startup',not exceptions,exceptions)
  check('zero network requests',not requests,requests)
  check('private export buttons enabled',all([await page.locator('#'+x).is_enabled() for x in ['exportIssues','exportReport','exportAI']]))
  async with page.expect_download() as d:await page.click('#exportIssues')
  s=pathlib.Path(await(await d.value).path()).read_text()
  check('CSV contains private exception data and header','record_key_PRIVATE' in s and 'A-2' in s and 'qty => units' in s)
  check('CSV includes mismatch cells', '7' in s and '4' in s)
  async with page.expect_download() as d:await page.click('#exportReport')
  txt=pathlib.Path(await(await d.value).path()).read_text()
  check('TXT clearly says no approval','NOT ACCEPTANCE' in txt and 'DO NOT share' in txt)
  async with page.expect_download() as d:await page.click('#exportAI')
  ai=json.loads(pathlib.Path(await(await d.value).path()).read_text())
  check('AI schema matches',ai['schema']=='PD-RECON-1')
  check('AI counts-only categories',ai['pairedRecords']==2 and ai['exceptionCounts']['VALUE_MISMATCH']==1)
  check('AI flags never grant authority',all(ai[x] is False for x in ['sourceAuthorityVerified','destinationAuthorityVerified','realWorldCorrectnessVerified','dataWriteAuthorized','clientContactAuthorized','publicReleaseAuthorized','containsRawRecords','containsRecordKeys','instructionAuthority']))
  check('AI omits raw records and keys','A-2' not in json.dumps(ai) and 'Widget' not in json.dumps(ai) and 'product_name' not in json.dumps(ai))
  await page.click('#demoClean')
  check('matching example has zero exceptions',await page.locator('#mIssues').inner_text()=='0')
  check('matching example remains unverified','UNVERIFIED' in await page.locator('#status').inner_text())
  await calc(SS,DD)
  check('equal rows actually pair 2',await page.locator('#mMatched').inner_text()=='2')
  await calc(SS,DD.replace('Widget B','Widget B changed'))
  check('changed value flagged','VALUE_MISMATCH' in await codes())
  await calc(SS,DD.replace('A-2,Widget B,4','A-2,Widget B,5'))
  check('changed numeric text flagged','VALUE_MISMATCH' in await codes())
  await calc(SS,DD.replace('A-2','A-1'))
  c=await codes();check('duplicate target keys flagged',c.count('DUPLICATE_KEY')==2,c)
  check('ambiguous target key not paired',await page.locator('#mMatched').inner_text()=='0')
  await calc(SS.replace('A-2,Widget B,4','A-1,Widget B,4'),DD)
  check('duplicate source keys flagged','DUPLICATE_KEY' in await codes())
  await calc(SS,DD.replace('A-2,Widget B,4',' ,Widget B,4'))
  check('blank destination key flagged','BLANK_KEY' in await codes())
  await calc(SS,DD.replace('A-2','A-2 ').replace('Widget B','widget b'),mode='fold')
  check('case folding and trimming work',await page.locator('#mIssues').inner_text()=='0')
  await calc(SS,DD.replace('A-2','A-2 ').replace('Widget B','widget b'),mode='exact')
  check('strict mode detects untrimmed key and value','MISSING_DESTINATION' in await codes() and 'EXTRA_DESTINATION' in await codes())
  await calc(SS,'\ufeff'+DD,mode='trim')
  check('BOM on destination is handled',await page.locator('#mIssues').inner_text()=='0')
  await calc(SS,DD,fields='qty => units')
  check('one mapped pair works',await page.locator('#mCompared').inner_text()=='2')
  await calc(SS,DD,fields='qty => units\nqty => product_name')
  await blocked('repeated source mapping disallowed')
  await calc(SS,DD,fields='label => units\nqty => units')
  await blocked('repeated target mapping disallowed')
  await calc(SS,DD,fields='missing => units')
  await blocked('unknown column held')
  await calc(SS,DD,fields='foo')
  await blocked('invalid mapping grammar held')
  await calc(SS,DD,fields='item_id => product_code')
  await blocked('key fields cannot masquerade as compared values')
  await calc(SS,DD,keyS='nonexistent',fields='label => product_name')
  await blocked('missing source key header fails')
  await calc(SS,DD,keyS='item_id',keyT='nope')
  await blocked('missing destination key header fails')
  await calc(SS,DD,keyT='product_code')
  check('restored key works',await page.locator('#mIssues').inner_text()=='0')
  await calc(SH+'\n',DD)
  await blocked('empty source data rejected')
  await calc(SH+'\nA-1,a,2,EXTRA',DD)
  await blocked('extra CSV columns rejected')
  await calc('item_id,item_id,qty\nA-1,a,2',DD)
  await blocked('duplicate headers rejected')
  await calc('item_id,,qty\nA-1,a,2',DD)
  await blocked('blank headers rejected')
  await calc(SH+'\nA-1,"unclosed,2',DD)
  await blocked('unclosed quoting rejected')
  await calc(SH+'\nA-1,a,'+'x'*2001,DD)
  await blocked('oversized cell rejected')
  await calc(SH+'\n'+'\n'.join('R-'+str(i)+',a,2' for i in range(1001)),DD)
  await blocked('1001 rows rejected')
  await calc(SH+'\n'+'A-1,a,2\n',DD)
  check('row after trailing newline accepted',await page.locator('#mSource').inner_text()=='1')
  await calc(SH+'\nA-1,"a,b",2',DH+'\nA-1,"a,b",2')
  check('quoted commas parsed',await page.locator('#mIssues').inner_text()=='0')
  await calc(SH+'\nA-1,"multi\nline",2',DH+'\nA-1,"multi\nline",2')
  check('quoted embedded newlines parsed',await page.locator('#mIssues').inner_text()=='0')
  await calc(SH+'\nA-1,"=HYPERLINK(\"\"a\"\")",2',DD.replace('Widget A','=HYPERLINK("a")'))
  check('formula-like input does not execute or crash',not exceptions,exceptions)
  await calc(SS,DD)
  await page.fill('#sourceText',SS.replace('Widget A','changed A'))
  check('changing input locks old exports',await page.locator('#exportAI').is_disabled() and 'Inputs changed' in await page.locator('#status').inner_text())
  await calc(SS,DD)
  f=ROOT/'examples/reconcile_source_fictional.csv'
  await page.locator('#sourceFile').set_input_files(str(f))
  await asyncio.sleep(0.25)
  check('local file picker loads source', 'A-3' in await page.locator('#sourceText').input_value())
  check('file change invalidates old export',await page.locator('#exportAI').is_disabled())
  await calc(SS.replace('Widget B','<img src=x onerror=alert(1)>'),DD)
  check('untrusted markup rendered as text',await page.locator('#results img').count()==0 and 'VALUE_MISMATCH' in await codes())
  check('no external network after adversarial input',not requests,requests)
  check('no script exceptions after adversarial tests',not exceptions,exceptions)
  await browser.close()
async def main():
 try:await suite()
 except BaseException as e:TESTS.append({'test':'UNCAUGHT','pass':False,'detail':repr(e)+'\n'+traceback.format_exc()[-3000:]})
 out={'suite':'recon_browser_checks','tests':len(TESTS),'passed':sum(x['pass'] for x in TESTS),'failed':sum(not x['pass'] for x in TESTS),'results':TESTS}
 (ROOT/'tests/recon_test_results.json').write_text(json.dumps(out,indent=2));print('RECON',out['passed'],'/',out['tests'])
 if out['failed']:
  for x in TESTS:
   if not x['pass']:print('FAIL',x)
  raise SystemExit(1)
if __name__=='__main__':asyncio.run(main())
